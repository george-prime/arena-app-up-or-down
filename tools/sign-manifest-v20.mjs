// BITCOIN UP OR DOWN'S MANIFEST VERSION 20, SIGNED BY ITS DEVELOPER: version 19 in every term but its clients - only the pages whose
// comments carry no names and no ticket numbers (client/index-v17.html, index-v18.html, index-v19.html); the older pages stay pinned by
// the versions that name them. Parent: version 19.
//
//   node tools/sign-manifest-v20.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/btc-updown-v20.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V19, GAME_ID_V19 } from '../plugin/btc-updown-v19.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';
import { UPDOWN_CLIENT_V17_HASH, UPDOWN_CLIENT_V18_HASH, UPDOWN_CLIENT_V19_HASH } from '../plugin/market-terms.js';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v20.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V19.gameDevPubkey)) throw new Error(`that key is not Up/Down's developer key ${toHex(MANIFEST_V19.gameDevPubkey).slice(0, 16)}`);
const clean = [UPDOWN_CLIENT_V17_HASH, UPDOWN_CLIENT_V18_HASH, UPDOWN_CLIENT_V19_HASH].map((h) => new Uint8Array(h));
for (const [n, h] of [[17, clean[0]], [18, clean[1]], [19, clean[2]]]) {
  if (!MANIFEST_V19.clients.some((c) => toHex(c) === toHex(h))) throw new Error(`client/index-v${n}.html is not a file version 19 pins`);
  const file = readFileSync(new URL(`../client/index-v${n}.html`, import.meta.url));
  const { createHash } = await import('node:crypto');
  if (createHash('sha256').update(file).digest('hex') !== toHex(h)) throw new Error(`client/index-v${n}.html does not hash to the pin`);
}
const { signature, ...v19body } = MANIFEST_V19;
void signature;
const body = { ...v19body, version: MANIFEST_V19.version + 1, parentManifestId: GAME_ID_V19,
  clients: clean.sort((x, y) => Buffer.compare(Buffer.from(x), Buffer.from(y))) };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V19) ? MANIFEST_V19 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/btc-updown-v20.js', import.meta.url), `// GENERATED by tools/sign-manifest-v20.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// btc-updown-15m's GameManifest version 20: version 19 (${toHex(GAME_ID_V19)}) in every term but its clients - only
// ${body.clients.map((c) => toHex(c).slice(0, 16)).join(', ')} (client/index-v17.html, -v18, -v19); requires protocol version ${body.requiredProtocolVersion}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1 } from './btc-updown.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V20_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V20 = decodeManifest(fromHex(MANIFEST_V20_HEX));
export const GAME_ID_V20 = gameIdOf(MANIFEST_V20);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V20, gameId: GAME_ID_V20 });
`);
console.log(`btc-updown-15m v${body.version}: parent ${toHex(GAME_ID_V19).slice(0, 16)}, clients ${body.clients.map((c) => toHex(c).slice(0, 8)).join(' ')}, game_id ${id}`);
