// BITCOIN UP OR DOWN'S MANIFEST VERSION 21, SIGNED BY ITS DEVELOPER: version 20 in every term, with the new client
// client/index-v21.html (each order's times from the press) beside version 20's three. Parent: version 20.
//
//   node tools/sign-manifest-v21.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/btc-updown-v21.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V20, GAME_ID_V20 } from '../plugin/btc-updown-v20.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';
import { UPDOWN_CLIENT_V21_HASH } from '../plugin/market-terms.js';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v21.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V20.gameDevPubkey)) throw new Error(`that key is not Up/Down's developer key ${toHex(MANIFEST_V20.gameDevPubkey).slice(0, 16)}`);
const v21 = new Uint8Array(UPDOWN_CLIENT_V21_HASH);
const { signature, ...v20body } = MANIFEST_V20;
void signature;
const body = { ...v20body, version: MANIFEST_V20.version + 1, parentManifestId: GAME_ID_V20,
  clients: [...MANIFEST_V20.clients.map((c) => new Uint8Array(c)), v21].sort((x, y) => Buffer.compare(Buffer.from(x), Buffer.from(y))) };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V20) ? MANIFEST_V20 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/btc-updown-v21.js', import.meta.url), `// GENERATED by tools/sign-manifest-v21.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// btc-updown-15m's GameManifest version 21: version 20 (${toHex(GAME_ID_V20)}) in every term, with the new client
// ${toHex(v21)} (each order's times) beside version 20's; requires protocol version ${body.requiredProtocolVersion}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1 } from './btc-updown.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V21_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V21 = decodeManifest(fromHex(MANIFEST_V21_HEX));
export const GAME_ID_V21 = gameIdOf(MANIFEST_V21);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V21, gameId: GAME_ID_V21 });
`);
console.log(`btc-updown-15m v${body.version}: parent ${toHex(GAME_ID_V20).slice(0, 16)}, clients ${body.clients.map((c) => toHex(c).slice(0, 8)).join(' ')}, game_id ${id}`);
