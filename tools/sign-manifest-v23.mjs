// BITCOIN UP OR DOWN'S MANIFEST VERSION 23, SIGNED BY ITS DEVELOPER: version 22 in every term, with the new client
// client/index-v23.html (each order's transaction id, short, to the explorer; times kept after a reload) beside version 22's five. Parent: version 22.
//
//   node tools/sign-manifest-v23.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/btc-updown-v23.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V22, GAME_ID_V22 } from '../plugin/btc-updown-v22.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';
import { UPDOWN_CLIENT_V23_HASH } from '../plugin/market-terms.js';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v23.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V22.gameDevPubkey)) throw new Error(`that key is not Up/Down's developer key ${toHex(MANIFEST_V22.gameDevPubkey).slice(0, 16)}`);
const v23 = new Uint8Array(UPDOWN_CLIENT_V23_HASH);
const { signature, ...v22body } = MANIFEST_V22;
void signature;
const body = { ...v22body, version: MANIFEST_V22.version + 1, parentManifestId: GAME_ID_V22,
  clients: [...MANIFEST_V22.clients.map((c) => new Uint8Array(c)), v23].sort((x, y) => Buffer.compare(Buffer.from(x), Buffer.from(y))) };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V22) ? MANIFEST_V22 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/btc-updown-v23.js', import.meta.url), `// GENERATED by tools/sign-manifest-v23.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// btc-updown-15m's GameManifest version 23: version 22 (${toHex(GAME_ID_V22)}) in every term, with the new client
// ${toHex(v23)} (each order's transaction id to the explorer) beside version 22's; requires protocol version ${body.requiredProtocolVersion}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1 } from './btc-updown.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V23_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V23 = decodeManifest(fromHex(MANIFEST_V23_HEX));
export const GAME_ID_V23 = gameIdOf(MANIFEST_V23);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V23, gameId: GAME_ID_V23 });
`);
console.log(`btc-updown-15m v${body.version}: parent ${toHex(GAME_ID_V22).slice(0, 16)}, clients ${body.clients.map((c) => toHex(c).slice(0, 8)).join(' ')}, game_id ${id}`);
