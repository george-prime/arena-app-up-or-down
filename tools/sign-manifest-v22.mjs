// BITCOIN UP OR DOWN'S MANIFEST VERSION 22, SIGNED BY ITS DEVELOPER: version 21 in every term, with the new client
// client/index-v22.html (the card's times named submitted, placed, lock) beside version 21's four. Parent: version 21.
//
//   node tools/sign-manifest-v22.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/btc-updown-v22.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V21, GAME_ID_V21 } from '../plugin/btc-updown-v21.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';
import { UPDOWN_CLIENT_V22_HASH } from '../plugin/market-terms.js';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v22.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V21.gameDevPubkey)) throw new Error(`that key is not Up/Down's developer key ${toHex(MANIFEST_V21.gameDevPubkey).slice(0, 16)}`);
const v22 = new Uint8Array(UPDOWN_CLIENT_V22_HASH);
const { signature, ...v21body } = MANIFEST_V21;
void signature;
const body = { ...v21body, version: MANIFEST_V21.version + 1, parentManifestId: GAME_ID_V21,
  clients: [...MANIFEST_V21.clients.map((c) => new Uint8Array(c)), v22].sort((x, y) => Buffer.compare(Buffer.from(x), Buffer.from(y))) };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V21) ? MANIFEST_V21 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/btc-updown-v22.js', import.meta.url), `// GENERATED by tools/sign-manifest-v22.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// btc-updown-15m's GameManifest version 22: version 21 (${toHex(GAME_ID_V21)}) in every term, with the new client
// ${toHex(v22)} (the card's times named as the note names them) beside version 21's; requires protocol version ${body.requiredProtocolVersion}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1 } from './btc-updown.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V22_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V22 = decodeManifest(fromHex(MANIFEST_V22_HEX));
export const GAME_ID_V22 = gameIdOf(MANIFEST_V22);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V22, gameId: GAME_ID_V22 });
`);
console.log(`btc-updown-15m v${body.version}: parent ${toHex(GAME_ID_V21).slice(0, 16)}, clients ${body.clients.map((c) => toHex(c).slice(0, 8)).join(' ')}, game_id ${id}`);
