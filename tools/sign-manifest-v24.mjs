// BITCOIN UP OR DOWN'S MANIFEST VERSION 24, SIGNED BY ITS DEVELOPER: version 23 in every term but who attests its outcome - no fixed keys
// any more: each round's 7 attestors are drawn from its census, an outcome standing with 5 of them (kanban #630, Daniel 2026-10-24:
// "pre deterministic and drawed randomly, not a fixed set of nodes ... 5 of 7"). Requires protocol version 21. Parent: version 23.
//
//   node tools/sign-manifest-v24.mjs <dev dir holding game-dev.pkcs8>
//
// Writes only public bytes: plugin/btc-updown-v24.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V23, GAME_ID_V23 } from '../plugin/btc-updown-v23.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v24.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V23.gameDevPubkey)) throw new Error(`that key is not Up/Down's developer key ${toHex(MANIFEST_V23.gameDevPubkey).slice(0, 16)}`);
const { signature, ...v23body } = MANIFEST_V23;
void signature;
const body = { ...v23body, version: MANIFEST_V23.version + 1, parentManifestId: GAME_ID_V23,
  attestors: [], attestThreshold: 0, attestDraw: { count: 7, threshold: 5 }, requiredProtocolVersion: 21 };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V23) ? MANIFEST_V23 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/btc-updown-v24.js', import.meta.url), `// GENERATED by tools/sign-manifest-v24.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// btc-updown-15m's GameManifest version 24: version 23 (${toHex(GAME_ID_V23)}) in every term but its attestors - none named: each round
// draws 7 from its census, 5 of them decide (kanban #630); requires protocol version ${body.requiredProtocolVersion}.
// Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it and never signs.
// game_id ${id}
import { GAME as V1 } from './btc-updown.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V24_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V24 = decodeManifest(fromHex(MANIFEST_V24_HEX));
export const GAME_ID_V24 = gameIdOf(MANIFEST_V24);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V24, gameId: GAME_ID_V24 });
`);
console.log(`btc-updown-15m v${body.version}: parent ${toHex(GAME_ID_V23).slice(0, 16)}, attestors drawn 5 of 7, protocol ${body.requiredProtocolVersion}, game_id ${id}`);
